-- =============================================================
-- PART B: Scoring Procedure + Task
-- Output columns from DETECT_ANOMALIES: SERIES, TS, Y, FORECAST,
-- LOWER_BOUND, UPPER_BOUND, IS_ANOMALY, PERCENTILE, DISTANCE
-- =============================================================

CREATE OR REPLACE PROCEDURE ML.DETECT_ANOMALIES()
RETURNS STRING
LANGUAGE SQL
EXECUTE AS CALLER
AS
BEGIN
  CREATE OR REPLACE TEMPORARY TABLE ML.TMP_SCORE_VIB AS
  SELECT ASSET_ID,
         TIME_SLICE(MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START') AS MINUTE_TS,
         AVG(VIB_RMS_MEAN) AS VIB_RMS_MEAN
  FROM FEATURES.DT_SENSOR_1MIN
  WHERE MINUTE_TS >= DATEADD('HOUR', -24, CURRENT_TIMESTAMP())
    AND VIB_RMS_MEAN IS NOT NULL
  GROUP BY ASSET_ID, TIME_SLICE(MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START');

  CREATE OR REPLACE TEMPORARY TABLE ML.TMP_VIB_RESULTS AS
  SELECT * FROM TABLE(
    ML.AD_VIBRATION!DETECT_ANOMALIES(
      INPUT_DATA => SYSTEM$REFERENCE('TABLE', 'ML.TMP_SCORE_VIB'),
      SERIES_COLNAME => 'ASSET_ID',
      TIMESTAMP_COLNAME => 'MINUTE_TS',
      TARGET_COLNAME => 'VIB_RMS_MEAN'
    )
  );

  CREATE OR REPLACE TEMPORARY TABLE ML.TMP_SCORE_TEMP AS
  SELECT ASSET_ID,
         TIME_SLICE(MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START') AS MINUTE_TS,
         AVG(TEMP_C_MEAN) AS TEMP_C_MEAN
  FROM FEATURES.DT_SENSOR_1MIN
  WHERE MINUTE_TS >= DATEADD('HOUR', -24, CURRENT_TIMESTAMP())
    AND TEMP_C_MEAN IS NOT NULL
  GROUP BY ASSET_ID, TIME_SLICE(MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START');

  CREATE OR REPLACE TEMPORARY TABLE ML.TMP_TEMP_RESULTS AS
  SELECT * FROM TABLE(
    ML.AD_TEMPERATURE!DETECT_ANOMALIES(
      INPUT_DATA => SYSTEM$REFERENCE('TABLE', 'ML.TMP_SCORE_TEMP'),
      SERIES_COLNAME => 'ASSET_ID',
      TIMESTAMP_COLNAME => 'MINUTE_TS',
      TARGET_COLNAME => 'TEMP_C_MEAN'
    )
  );

  CREATE OR REPLACE TEMPORARY TABLE ML.TMP_SCORE_RPM AS
  SELECT ASSET_ID,
         TIME_SLICE(MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START') AS MINUTE_TS,
         AVG(RPM_MEAN) AS RPM_MEAN
  FROM FEATURES.DT_SENSOR_1MIN
  WHERE MINUTE_TS >= DATEADD('HOUR', -24, CURRENT_TIMESTAMP())
    AND RPM_MEAN IS NOT NULL
  GROUP BY ASSET_ID, TIME_SLICE(MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START');

  CREATE OR REPLACE TEMPORARY TABLE ML.TMP_RPM_RESULTS AS
  SELECT * FROM TABLE(
    ML.AD_RPM!DETECT_ANOMALIES(
      INPUT_DATA => SYSTEM$REFERENCE('TABLE', 'ML.TMP_SCORE_RPM'),
      SERIES_COLNAME => 'ASSET_ID',
      TIMESTAMP_COLNAME => 'MINUTE_TS',
      TARGET_COLNAME => 'RPM_MEAN'
    )
  );

  MERGE INTO ML.ANOMALY_EVENTS tgt
  USING (
    SELECT SERIES AS ASSET_ID, TS::TIMESTAMP_TZ AS TS, 'vibration_rms' AS SERIES_NAME,
           IS_ANOMALY, DISTANCE, PERCENTILE, FORECAST, LOWER_BOUND AS LOWER, UPPER_BOUND AS UPPER
    FROM ML.TMP_VIB_RESULTS
    UNION ALL
    SELECT SERIES, TS::TIMESTAMP_TZ, 'temp_c',
           IS_ANOMALY, DISTANCE, PERCENTILE, FORECAST, LOWER_BOUND, UPPER_BOUND
    FROM ML.TMP_TEMP_RESULTS
    UNION ALL
    SELECT SERIES, TS::TIMESTAMP_TZ, 'rpm',
           IS_ANOMALY, DISTANCE, PERCENTILE, FORECAST, LOWER_BOUND, UPPER_BOUND
    FROM ML.TMP_RPM_RESULTS
  ) src
  ON tgt.ASSET_ID = src.ASSET_ID AND tgt.TS = src.TS AND tgt.SERIES_NAME = src.SERIES_NAME
  WHEN MATCHED THEN UPDATE SET
    IS_ANOMALY = src.IS_ANOMALY, DISTANCE = src.DISTANCE,
    PERCENTILE = src.PERCENTILE, FORECAST = src.FORECAST,
    LOWER = src.LOWER, UPPER = src.UPPER
  WHEN NOT MATCHED THEN INSERT VALUES
    (src.ASSET_ID, src.TS, src.SERIES_NAME, src.IS_ANOMALY, src.DISTANCE,
     src.PERCENTILE, src.FORECAST, src.LOWER, src.UPPER);

  RETURN 'DETECT_ANOMALIES complete';
END;

CREATE OR REPLACE TASK ML.TASK_DETECT_ANOMALIES
  WAREHOUSE = AEGIS_WH
  SCHEDULE  = '5 MINUTE'
AS
  CALL ML.DETECT_ANOMALIES();

