-- Training views: exclude ground-truth degradation spans (date-range
-- exclusion only, NO labels leak into features).
CREATE OR REPLACE VIEW ML.V_TRAIN_VIB_HEALTHY AS
SELECT
  s.ASSET_ID,
  TIME_SLICE(s.MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START') AS MINUTE_TS,
  AVG(s.VIB_RMS_MEAN) AS VIB_RMS_MEAN
FROM FEATURES.DT_SENSOR_1MIN s
WHERE s.VIB_RMS_MEAN IS NOT NULL
  AND s.MINUTE_TS < '2026-07-15'::TIMESTAMP_TZ
  AND NOT EXISTS (
    SELECT 1 FROM TEST.GROUND_TRUTH_FAILURES g
    WHERE g.ASSET_ID = s.ASSET_ID
      AND s.MINUTE_TS >= g.DEGRADATION_START_TS
      AND s.MINUTE_TS <= g.FAILURE_TS
  )
GROUP BY s.ASSET_ID, TIME_SLICE(s.MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START');

CREATE OR REPLACE VIEW ML.V_TRAIN_TEMP_HEALTHY AS
SELECT
  s.ASSET_ID,
  TIME_SLICE(s.MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START') AS MINUTE_TS,
  AVG(s.TEMP_C_MEAN) AS TEMP_C_MEAN
FROM FEATURES.DT_SENSOR_1MIN s
WHERE s.TEMP_C_MEAN IS NOT NULL
  AND s.MINUTE_TS < '2026-07-15'::TIMESTAMP_TZ
  AND NOT EXISTS (
    SELECT 1 FROM TEST.GROUND_TRUTH_FAILURES g
    WHERE g.ASSET_ID = s.ASSET_ID
      AND s.MINUTE_TS >= g.DEGRADATION_START_TS
      AND s.MINUTE_TS <= g.FAILURE_TS
  )
GROUP BY s.ASSET_ID, TIME_SLICE(s.MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START');

CREATE OR REPLACE VIEW ML.V_TRAIN_RPM_HEALTHY AS
SELECT
  s.ASSET_ID,
  TIME_SLICE(s.MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START') AS MINUTE_TS,
  AVG(s.RPM_MEAN) AS RPM_MEAN
FROM FEATURES.DT_SENSOR_1MIN s
WHERE s.RPM_MEAN IS NOT NULL
  AND s.MINUTE_TS < '2026-07-15'::TIMESTAMP_TZ
  AND NOT EXISTS (
    SELECT 1 FROM TEST.GROUND_TRUTH_FAILURES g
    WHERE g.ASSET_ID = s.ASSET_ID
      AND s.MINUTE_TS >= g.DEGRADATION_START_TS
      AND s.MINUTE_TS <= g.FAILURE_TS
  )
GROUP BY s.ASSET_ID, TIME_SLICE(s.MINUTE_TS::TIMESTAMP_NTZ, 5, 'MINUTE', 'START');

