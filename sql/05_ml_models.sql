-- =============================================================
-- PART F: Risk Fusion — DT_ASSET_HEALTH v2
-- Fuses rule-based health, ML anomaly distance, z-score
-- persistence, and asset criticality.
-- =============================================================

CREATE OR REPLACE DYNAMIC TABLE FEATURES.DT_ASSET_HEALTH
  TARGET_LAG = '5 minutes'
  WAREHOUSE = AEGIS_WH
AS
WITH latest_ts AS (
  SELECT asset_id, MAX(window_ts) AS max_window_ts
  FROM FEATURES.DT_SENSOR_FEATURES_15MIN
  GROUP BY asset_id
),
latest_features AS (
  SELECT f.*
  FROM FEATURES.DT_SENSOR_FEATURES_15MIN f
  JOIN latest_ts lt ON f.asset_id = lt.asset_id AND f.window_ts = lt.max_window_ts
),
recent_downtime AS (
  SELECT asset_id, SUM(minutes) AS recent_down_min
  FROM CORE.DOWNTIME_EVENT
  WHERE is_planned = FALSE AND end_ts >= DATEADD('DAY', -7, CURRENT_TIMESTAMP())
  GROUP BY asset_id
),
rule_scored AS (
  SELECT
    lf.asset_id, lf.window_ts AS last_reading_ts, a.criticality,
    lf.vib_rms_zscore, lf.temp_c_zscore, lf.rpm_zscore,
    GREATEST(0, LEAST(100,
      100
      - CASE WHEN lf.vib_rms_mean >= a.vib_danger_mm_s THEN 40
             WHEN lf.vib_rms_mean >= a.vib_alert_mm_s  THEN 20 + 20 * LEAST(1.0,
                   (lf.vib_rms_mean - a.vib_alert_mm_s) / NULLIF(a.vib_danger_mm_s - a.vib_alert_mm_s, 0))
             WHEN lf.vib_rms_mean >= a.vib_alert_mm_s * 0.8 THEN 10 ELSE 0 END
      - CASE WHEN lf.temp_c_mean >= a.temp_limit_c       THEN 25
             WHEN lf.temp_c_mean >= a.temp_limit_c * 0.9 THEN 15
             WHEN lf.temp_c_mean >= a.temp_limit_c * 0.8 THEN 5 ELSE 0 END
      - CASE WHEN ABS(COALESCE(lf.vib_rms_zscore, 0)) > 3   THEN 15
             WHEN ABS(COALESCE(lf.vib_rms_zscore, 0)) > 2   THEN 10
             WHEN ABS(COALESCE(lf.vib_rms_zscore, 0)) > 1.5 THEN 5 ELSE 0 END
      - CASE WHEN COALESCE(rd.recent_down_min, 0) > 480 THEN 10
             WHEN COALESCE(rd.recent_down_min, 0) > 120 THEN 5 ELSE 0 END
      - CASE WHEN COALESCE(lf.rpm_variance, 0) > 10000 THEN 10
             WHEN COALESCE(lf.rpm_variance, 0) > 5000  THEN 5 ELSE 0 END
    )) AS rule_health_score
  FROM latest_features lf
  JOIN CORE.ASSET a ON lf.asset_id = a.asset_id
  LEFT JOIN recent_downtime rd ON lf.asset_id = rd.asset_id
),
anomaly_evidence AS (
  SELECT ASSET_ID,
    MAX(CASE WHEN SERIES_NAME = 'vibration_rms' AND IS_ANOMALY THEN DISTANCE ELSE 0 END) AS vib_anomaly_dist,
    MAX(CASE WHEN SERIES_NAME = 'temp_c'        AND IS_ANOMALY THEN DISTANCE ELSE 0 END) AS temp_anomaly_dist,
    MAX(CASE WHEN SERIES_NAME = 'rpm'           AND IS_ANOMALY THEN DISTANCE ELSE 0 END) AS rpm_anomaly_dist,
    COUNT(CASE WHEN IS_ANOMALY THEN 1 END) AS anomaly_count_6h
  FROM ML.ANOMALY_EVENTS
  WHERE TS >= DATEADD('HOUR', -6, CURRENT_TIMESTAMP())
  GROUP BY ASSET_ID
),
fused AS (
  SELECT rs.asset_id, rs.last_reading_ts, rs.criticality, rs.rule_health_score,
    GREATEST(COALESCE(ae.vib_anomaly_dist,0), COALESCE(ae.temp_anomaly_dist,0), COALESCE(ae.rpm_anomaly_dist,0)) AS max_anomaly_distance,
    GREATEST(ABS(COALESCE(rs.vib_rms_zscore,0)), ABS(COALESCE(rs.temp_c_zscore,0)), ABS(COALESCE(rs.rpm_zscore,0))) AS max_zscore,
    COALESCE(ae.anomaly_count_6h, 0) AS anomaly_count_6h,
    CASE
      WHEN GREATEST(COALESCE(ae.vib_anomaly_dist,0), COALESCE(ae.temp_anomaly_dist,0), COALESCE(ae.rpm_anomaly_dist,0)) = 0 THEN NULL
      WHEN COALESCE(ae.vib_anomaly_dist,0) >= COALESCE(ae.temp_anomaly_dist,0)
        AND COALESCE(ae.vib_anomaly_dist,0) >= COALESCE(ae.rpm_anomaly_dist,0) THEN 'BEARING_WEAR'
      WHEN COALESCE(ae.temp_anomaly_dist,0) >= COALESCE(ae.rpm_anomaly_dist,0) THEN 'COOLING_RESTRICTION'
      ELSE 'RPM_INSTABILITY'
    END AS predicted_mode
  FROM rule_scored rs
  LEFT JOIN anomaly_evidence ae ON rs.asset_id = ae.ASSET_ID
)
SELECT
  asset_id, last_reading_ts,
  GREATEST(0, LEAST(100,
    rule_health_score - LEAST(20, max_anomaly_distance * 5)
    - CASE WHEN anomaly_count_6h > 10 THEN 10 WHEN anomaly_count_6h > 5 THEN 5 ELSE 0 END
  ))::FLOAT AS health_score,
  max_anomaly_distance::FLOAT AS anomaly_distance,
  LEAST(1.0, GREATEST(0,
    (max_anomaly_distance / 10.0) * 0.4
    + (LEAST(max_zscore, 5.0) / 5.0) * 0.3
    + (anomaly_count_6h / 50.0) * 0.2
    + (criticality / 5.0) * 0.1
  ))::FLOAT AS failure_probability_24h,
  predicted_mode,
  CASE
    WHEN GREATEST(0, LEAST(100, rule_health_score - LEAST(20, max_anomaly_distance * 5)
           - CASE WHEN anomaly_count_6h > 10 THEN 10 WHEN anomaly_count_6h > 5 THEN 5 ELSE 0 END)) <= 30 THEN 'CRITICAL'
    WHEN GREATEST(0, LEAST(100, rule_health_score - LEAST(20, max_anomaly_distance * 5)
           - CASE WHEN anomaly_count_6h > 10 THEN 10 WHEN anomaly_count_6h > 5 THEN 5 ELSE 0 END)) <= 50 THEN 'HIGH'
    WHEN GREATEST(0, LEAST(100, rule_health_score - LEAST(20, max_anomaly_distance * 5)
           - CASE WHEN anomaly_count_6h > 10 THEN 10 WHEN anomaly_count_6h > 5 THEN 5 ELSE 0 END)) <= 70 THEN 'MEDIUM'
    ELSE 'LOW'
  END AS risk_level
FROM fused;

