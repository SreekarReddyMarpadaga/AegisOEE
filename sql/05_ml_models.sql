-- =============================================================
-- PART D: Z-Score Fallback Detector
-- Flags anomalies when |z-score| > 2.5 for 3+ consecutive
-- 15-min windows. Writes to same ANOMALY_EVENTS format.
-- =============================================================

CREATE OR REPLACE PROCEDURE ML.DETECT_ZSCORE_ANOMALIES()
RETURNS STRING
LANGUAGE SQL
EXECUTE AS CALLER
AS
BEGIN
  MERGE INTO ML.ANOMALY_EVENTS tgt
  USING (
    WITH scored AS (
      SELECT ASSET_ID, WINDOW_TS, VIB_RMS_ZSCORE, TEMP_C_ZSCORE, RPM_ZSCORE,
        LAG(VIB_RMS_ZSCORE, 1) OVER (PARTITION BY ASSET_ID ORDER BY WINDOW_TS) AS vib_z_lag1,
        LAG(VIB_RMS_ZSCORE, 2) OVER (PARTITION BY ASSET_ID ORDER BY WINDOW_TS) AS vib_z_lag2,
        LAG(TEMP_C_ZSCORE, 1) OVER (PARTITION BY ASSET_ID ORDER BY WINDOW_TS) AS temp_z_lag1,
        LAG(TEMP_C_ZSCORE, 2) OVER (PARTITION BY ASSET_ID ORDER BY WINDOW_TS) AS temp_z_lag2,
        LAG(RPM_ZSCORE, 1) OVER (PARTITION BY ASSET_ID ORDER BY WINDOW_TS) AS rpm_z_lag1,
        LAG(RPM_ZSCORE, 2) OVER (PARTITION BY ASSET_ID ORDER BY WINDOW_TS) AS rpm_z_lag2
      FROM FEATURES.DT_SENSOR_FEATURES_15MIN
      WHERE WINDOW_TS >= DATEADD('HOUR', -24, CURRENT_TIMESTAMP())
    )
    SELECT ASSET_ID, WINDOW_TS::TIMESTAMP_TZ AS TS, 'zscore_vibration' AS SERIES_NAME,
           TRUE AS IS_ANOMALY, ABS(VIB_RMS_ZSCORE) AS DISTANCE,
           NULL::FLOAT AS PERCENTILE, NULL::FLOAT AS FORECAST, NULL::FLOAT AS LOWER, NULL::FLOAT AS UPPER
    FROM scored WHERE ABS(VIB_RMS_ZSCORE) > 2.5 AND ABS(vib_z_lag1) > 2.5 AND ABS(vib_z_lag2) > 2.5
    UNION ALL
    SELECT ASSET_ID, WINDOW_TS::TIMESTAMP_TZ, 'zscore_temp', TRUE, ABS(TEMP_C_ZSCORE),
           NULL, NULL, NULL, NULL
    FROM scored WHERE ABS(TEMP_C_ZSCORE) > 2.5 AND ABS(temp_z_lag1) > 2.5 AND ABS(temp_z_lag2) > 2.5
    UNION ALL
    SELECT ASSET_ID, WINDOW_TS::TIMESTAMP_TZ, 'zscore_rpm', TRUE, ABS(RPM_ZSCORE),
           NULL, NULL, NULL, NULL
    FROM scored WHERE ABS(RPM_ZSCORE) > 2.5 AND ABS(rpm_z_lag1) > 2.5 AND ABS(rpm_z_lag2) > 2.5
  ) src
  ON tgt.ASSET_ID = src.ASSET_ID AND tgt.TS = src.TS AND tgt.SERIES_NAME = src.SERIES_NAME
  WHEN MATCHED THEN UPDATE SET IS_ANOMALY = src.IS_ANOMALY, DISTANCE = src.DISTANCE
  WHEN NOT MATCHED THEN INSERT VALUES
    (src.ASSET_ID, src.TS, src.SERIES_NAME, src.IS_ANOMALY, src.DISTANCE,
     src.PERCENTILE, src.FORECAST, src.LOWER, src.UPPER);

  RETURN 'Z-score anomaly detection complete';
END;

